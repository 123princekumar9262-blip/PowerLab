export const machineById = (id: string) => MACHINES.find((m) => m.id === id)

export interface MachineFilter {
  q: string
  family: Family | 'all'
  supply: Supply | 'all'
  role: 'all' | 'Motor' | 'Generator' | 'Other'
  level: MLevel | 'all'
}
export const NO_FILTER: MachineFilter = { q: '', family: 'all', supply: 'all', role: 'all', level: 'all' }

const norm = (s: string) => s.toLowerCase().normalize('NFKD').replace(/[̀-ͯ]/g, '')

/** Search and filters (pure: tested). Ready models first, then by the catalogue order. */
export function filterMachines(f: MachineFilter, list: MachineEntry[] = MACHINES): MachineEntry[] {
  const words = norm(f.q).split(/\s+/).filter(Boolean)
  const roleOk = (r: Role) => f.role === 'all' || (f.role === 'Other' ? r !== 'Motor' && r !== 'Generator' && r !== 'Motor / generator' : r === f.role || r === 'Motor / generator')
  return list
    .filter((m) => (f.family === 'all' || m.family === f.family) && (f.supply === 'all' || m.supply === f.supply) && roleOk(m.role) && (f.level === 'all' || m.level === f.level))
    .filter((m) => {
      const hay = norm(`${m.name} ${m.summary} ${m.keywords.join(' ')} ${m.subgroup}`)
      return words.every((w) => hay.includes(w))
    })
    .sort((a, b) => (a.status === b.status ? 0 : a.status === 'ready' ? -1 : 1))
}
