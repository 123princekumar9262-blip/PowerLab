/**
 * Engineering relationships used by the 3D Machines Lab — each one explicit, with its assumptions in the
 * caller's text, and unit-tested (tests/machines.test.ts). These are steady-state textbook relations, not a
 * simulation: the circuit labs simulate. A result the inputs cannot support is null, never invented.
 */

export const rpmFromRad = (w: number) => (w * 60) / (2 * Math.PI)
export const radFromRpm = (n: number) => (n * 2 * Math.PI) / 60

// ── Brushed DC motor (separately excited / permanent magnet), steady state ─────────────────────────────
/**
 * V = E + Ia·Ra,  E = kΦ·ω,  T = kΦ·Ia, and in steady state T = TL (friction and brush drop neglected).
 * Returns null quantities when the motor is stalled (TL above the stall torque kΦ·V/Ra).
 */
export function dcMotor(p: { va: number; kphi: number; ra: number; tl: number }) {
  const { va, kphi, ra, tl } = p
  const stallTorque = (kphi * va) / ra
  const noLoad = va / kphi // rad/s
  if (kphi <= 0 || ra <= 0) return null
  if (tl > stallTorque) {
    const ia = va / ra
    return { stalled: true as const, ia, e: 0, w: 0, n: 0, stallTorque, noLoad, pin: va * ia, pcu: ia * ia * ra, pout: 0, eff: 0 }
  }
  const ia = tl / kphi
  const e = va - ia * ra
  const w = e / kphi
  const pin = va * ia
  const pcu = ia * ia * ra
  const pout = tl * w
  return { stalled: false as const, ia, e, w, n: rpmFromRad(w), stallTorque, noLoad, pin, pcu, pout, eff: pin > 0 ? pout / pin : null }
}

// ── DC generator (separately excited / PM), steady state, resistive load ───────────────────────────────
/** E = kΦ·ω; Ia = E / (Ra + RL); terminal V = Ia·RL; the prime mover supplies T = kΦ·Ia. */
export function dcGenerator(p: { kphi: number; n: number; ra: number; rl: number }) {
  const w = radFromRpm(p.n)
  const e = p.kphi * w
  const ia = e / (p.ra + p.rl)
  const v = ia * p.rl
  return { w, e, ia, v, torque: p.kphi * ia, pout: v * ia, pmech: p.kphi * ia * w, pcu: ia * ia * p.ra }
}

// ── AC machines ───────────────────────────────────────────────────────────────────────────────────────
/** Synchronous speed Ns = 120·f / P [rpm], P = total number of poles. */
export const syncSpeed = (f: number, poles: number) => (120 * f) / poles
/** Slip s = (Ns − Nr) / Ns. */
export const slip = (ns: number, nr: number) => (ns - nr) / ns
/** Rotor speed from slip: Nr = (1 − s)·Ns. */
export const rotorSpeed = (ns: number, s: number) => (1 - s) * ns
/** Frequency generated by a synchronous machine: f = P·n / 120. */
export const genFrequency = (poles: number, n: number) => (poles * n) / 120

// ── Ideal transformer ────────────────────────────────────────────────────────────────────────────────
/** V2 = V1·N2/N1; with a resistive load I2 = V2/R, I1 = I2·N2/N1 (no magnetising current, no losses). */
export function idealTransformer(p: { v1: number; n1: number; n2: number; rl: number }) {
  const a = p.n1 / p.n2
  const v2 = p.v1 / a
  const i2 = v2 / p.rl
  const i1 = i2 / a
  return { a, v2, i2, i1, p: v2 * i2, rSeen: p.rl * a * a }
}
