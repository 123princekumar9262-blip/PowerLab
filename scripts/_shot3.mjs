import { chromium } from 'playwright'
const b = await chromium.launch({ channel: 'msedge' })
const p = await b.newPage({ viewport: { width: 1440, height: 1000 } })
const errs = []
p.on('pageerror', (e) => errs.push(String(e)))
p.on('console', (m) => m.type() === 'error' && errs.push(m.text()))
await p.goto('http://localhost:5199/')
await p.getByRole('tab', { name: 'Three-phase' }).click()
await p.getByRole('button', { name: /Run simulation/ }).click()
await p.waitForTimeout(600)
const av = await p.locator('.angle-svg').boundingBox()
await p.mouse.click(av.x + av.width * (44 + (75 / 360) * (720 - 56)) / 720, av.y + 60)
await p.waitForTimeout(300)
await p.screenshot({ path: 'scripts/out/3ph-03-angle.png', fullPage: false })
await p.getByRole('button', { name: /Physics Lens/ }).click()
await p.getByRole('button', { name: 'Next stage →' }).click()
await p.getByRole('button', { name: 'Next stage →' }).click()
await p.waitForTimeout(200)
await p.screenshot({ path: 'scripts/out/3ph-04-lens.png' })
console.log(errs.join('\n') || 'no errors')
await b.close()
