import { chromium } from 'playwright'
const b = await chromium.launch({ channel: 'msedge' })
const p = await b.newPage({ viewport: { width: 1440, height: 900 } })
const errs = []
p.on('pageerror', (e) => errs.push(String(e)))
p.on('console', (m) => m.type() === 'error' && errs.push(m.text()))
await p.goto('http://localhost:5199/')
await p.getByRole('tab', { name: 'Three-phase' }).click()
await p.getByRole('button', { name: /Run simulation/ }).click()
await p.waitForTimeout(800)
await p.screenshot({ path: 'scripts/out/3ph-01-bridge-r.png' })
await p.getByRole('radio', { name: '3-pulse', exact: true }).click()
await p.waitForTimeout(500)
await p.screenshot({ path: 'scripts/out/3ph-02-halfwave.png' })
console.log(errs.join('\n') || 'no errors')
await b.close()
