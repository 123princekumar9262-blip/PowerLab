import { chromium } from 'playwright'
const b = await chromium.launch({ channel: 'msedge' })
const p = await b.newPage({ viewport: { width: 390, height: 844 } })
await p.goto('http://localhost:5199/')
await p.getByRole('radio', { name: 'Half-wave', exact: true }).click()
await p.getByRole('radio', { name: 'R', exact: true }).click()
await p.getByRole('button', { name: /Run simulation/ }).click()
await p.waitForTimeout(800)
await p.getByRole('radio', { name: 'RL', exact: true }).click()
await p.waitForTimeout(400)
console.log('overflow', await p.evaluate(() => document.documentElement.scrollWidth - document.documentElement.clientWidth))
const wide = await p.evaluate(() => [...document.querySelectorAll('body *')].filter((e) => { for (let a = e.parentElement; a; a = a.parentElement) { const o = getComputedStyle(a).overflowX; if (o === 'auto' || o === 'scroll' || o === 'hidden') return false } return true }).map((e) => ({ e, r: e.getBoundingClientRect() })).filter((x) => x.r.right > 392).map((x) => `${x.e.tagName.toLowerCase()}.${[...x.e.classList].join('.')} right=${Math.round(x.r.right)} w=${Math.round(x.r.width)}`).slice(0, 12))
console.log(wide.join('\n'))
await b.close()
