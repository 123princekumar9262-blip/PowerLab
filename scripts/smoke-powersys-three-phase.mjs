// ── line constants from Module 8 (opt-in; the preset stays the default) ─────────────────────────────────────────
console.log('── Line constants source')
{
  const p3 = await browser.newPage({ viewport: { width: 1440, height: 900 } })
  p3.on('pageerror', (e) => errors.push(String(e)))
  p3.on('console', (m) => m.type() === 'error' && errors.push(m.text()))
  await p3.goto(URL)
  await p3.evaluate(() => localStorage.removeItem('pel.powersys.line'))
  await p3.goto(URL + MOD + '?mode=explore')
  await p3.waitForTimeout(900)
  await p3.locator('.ps-panel').getByRole('radio', { name: 'Transmission line', exact: true }).click()
  await p3.waitForTimeout(400)
  const src = p3.locator('.ps-3p-source')
  check((await src.getByRole('radio', { name: 'Preset' }).getAttribute('aria-checked')) === 'true', 'the preset is the default source')
  check(/Active: the 400 kV preset/.test(await src.innerText()) && /design a line in\s+Module 8/.test(await src.innerText()), 'with no Module 8 design: the preset is active and the way to Module 8 is shown')
  const before = await p3.locator('.ps-readouts').first().innerText()
  // a design sent from Module 8 (as Module 8 stores it)
  await p3.evaluate(() => localStorage.setItem('pel.powersys.line', JSON.stringify({ rOhmPerKm: 0.03, xOhmPerKm: 0.3, bUsPerKm: 3.8, kv: 400, fHz: 50, summary: 'test design', at: Date.now() })))
  await p3.reload()
  await p3.waitForTimeout(900)
  await p3.locator('.ps-panel').getByRole('radio', { name: 'Transmission line', exact: true }).click()
  await p3.waitForTimeout(400)
  check((await src.getByRole('radio', { name: 'Preset' }).getAttribute('aria-checked')) === 'true', 'a design in Module 8 does not switch the source by itself')
  await src.getByRole('radio', { name: 'Module 8 design' }).click()
  await p3.waitForTimeout(400)
  const active = await src.innerText()
  check(/Active: calculated in Module 8 — test design, 400 kV/.test(active) && /x 0\.3000 Ω\/km/.test(active), 'choosing Module 8 design: the active source and its constants are shown')
  const after = await p3.locator('.ps-readouts').first().innerText()
  check(after !== before, 'the results follow the designed constants')
  await src.getByRole('radio', { name: 'Preset' }).click()
  await p3.waitForTimeout(400)
  check((await p3.locator('.ps-readouts').first().innerText()) === before, 'back to Preset: the original numbers return exactly')
  await p3.evaluate(() => localStorage.removeItem('pel.powersys.line'))
  await p3.close()
}

