/**
 * Power Systems — Module 6, Stability & Frequency Control, in the browser: every mode, the key computed numbers,
 * activities, playback (and none under reduced motion), no console errors, no horizontal overflow.
 * Run with the dev server on 5199: node scripts/smoke-powersys-stability.mjs
 */
import { mkdirSync } from 'node:fs'
import { chromium } from 'playwright'

const OUT = 'scripts/out/'
mkdirSync(OUT, { recursive: true })
const errors = []
const failures = []
const check = (cond, msg) => {
  console.log(`  ${cond ? '✓' : '✗'} ${msg}`)
  if (!cond) failures.push(msg)
}
const URL = process.env.LAB_URL ?? 'http://localhost:5199/'
const PAGE = '#/subjects/power-systems/stability'
const browser = await chromium.launch({ channel: process.env.PW_CHANNEL ?? 'msedge' })
const page = await browser.newPage({ viewport: { width: 1440, height: 900 } })
page.on('console', (m) => m.type() === 'error' && errors.push(m.text()))
page.on('pageerror', (e) => errors.push(String(e)))
const wait = (ms = 400) => page.waitForTimeout(ms)
const go = async (h) => {
  await page.goto(URL + h)
  await wait(1000)
}
const noOverflow = () => page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth + 1)
const text = (sel) => page.locator(sel).first().innerText()
const readouts = () => page.locator('.ps-readouts').first().innerText()
const acts = async () => (await page.locator('.ps-acts summary').innerText()).replace(/\s+/g, ' ')

await page.goto(URL)
await page.evaluate(() => localStorage.clear())

// ── the module is listed as interactive ──────────────────────────────────────
console.log('── Subject page')
await go('#/subjects/power-systems')
const card = await page.locator('.subject-topic-card', { hasText: 'Stability' }).innerText()
check(/Interactive module/.test(card), 'Module 6 is listed as an interactive module')

// ── Learn ────────────────────────────────────────────────────────────────────
console.log('── Learn')
await go(PAGE)
check((await page.locator('main h1').first().innerText()) === 'Stability & Frequency Control', 'module heading')
check((await page.getByRole('tab').allInnerTexts()).join('|') === 'Learn|Explore|Experiment|Verify|Practise', 'five modes')
check(/Step 1 of 8/i.test(await text('.ps-stepper')), 'the tour has eight steps')
check(/δ₀ = 25\.87°/.test(await text('.ps-step-body')), 'step 1: δ₀ = 25.87° from asin(0.8 / 1.833)')
check((await page.locator('svg.ps-st-sld').count()) === 1 && (await page.locator('.ps-st-pd').count()) === 1, 'step 1 shows the system and its power–angle curve')
await page.screenshot({ path: OUT + 'st-learn-1.png', fullPage: true })
const next = () => page.getByRole('button', { name: 'Next →' }).click()
await next()
await wait(200)
check(/1\.146 Hz/.test(await text('.ps-step-body')) && /P_s = .*1\.650 pu\/rad/.test(await text('.ps-step-body')), 'step 2: P_s = 1.650 pu/rad, f_n = 1.146 Hz')
await next()
await wait(200)
check(/δ_c = 42\.1°/.test(await text('.ps-step-body')), 'step 3: cleared at 150 ms the rotor has reached 42.1°')
await next()
await wait(200)
check((await page.locator('.ps-st-area--acc').count()) >= 1 && (await page.locator('.ps-st-area--dec').count()) >= 1, 'step 4: the equal areas are shaded')
check(/accelerating area A₁ = 0\.2262 pu·rad/.test(await text('.ps-step-body')), 'step 4: A₁ = P_m·(δ_c − δ₀) = 0.2262 pu·rad')
await page.screenshot({ path: OUT + 'st-learn-4.png', fullPage: true })
await next()
await wait(200)
const s5 = await text('.ps-step-body')
check(/δ_cr = 57\.48°/.test(s5) && /209\.5 ms/.test(s5), 'step 5: δ_cr = 57.48°, t_cr = 209.5 ms (closed form and bisection)')
check(/loses synchronism/.test(s5), 'step 5: clearing at 250 ms loses synchronism')
await next()
await wait(200)
check(/−0\.500 Hz\/s/.test(await text('.ps-step-body')), 'step 6: RoCoF(0) = −0.500 Hz/s')
await next()
await wait(200)
check(/−0\.238 Hz/.test(await text('.ps-step-body')) && /nadir, −0\.368 Hz/.test(await text('.ps-step-body')), 'step 7: Δf_ss = −0.238 Hz, nadir −0.368 Hz')
await next()
await wait(200)
check(/after 24\.7 s/.test(await text('.ps-step-body')), 'step 8: AGC back within 5 % after 24.7 s')
await page.screenshot({ path: OUT + 'st-learn-8.png', fullPage: true })
check(/1 of 6/.test(await acts()), 'finishing the tour completes an activity')
check(await noOverflow(), 'Learn: no horizontal overflow')
await page.getByRole('button', { name: 'Run your own fault →' }).click()
await wait(600)
check((await page.evaluate(() => location.hash)) === PAGE + '?mode=explore', 'the tour leads on to Explore')

// ── Explore: rotor angle ─────────────────────────────────────────────────────
console.log('── Explore · rotor angle')
let ro = await readouts()
check(/Stable/.test(ro) && /209\.5\s*ms/.test(ro) && /margin \+59\.5 ms/.test(ro), 'default fault: stable, t_cr = 209.5 ms, margin +59.5 ms')
check(/0\.226 \/ 0\.476/.test(ro), 'areas: A₁ = 0.226, A₂ available = 0.476 pu·rad')
check(/t = 3\.000 s/.test(await text('.ps-st-now')), 'the whole run is shown at first (t = 3 s)')
const tc = page.locator('.ps-slider', { hasText: 'Clearing time' }).locator('input')
await tc.fill('0.25')
await wait(500)
ro = await readouts()
check(/Unstable/.test(ro) && /loses synchronism/.test(ro) && /margin −40\.5 ms/.test(ro), 'clearing at 250 ms: loses synchronism, margin −40.5 ms')
check(/2 of 6/.test(await acts()), 'a stable and an unstable clearing complete the “swing” activity')
await page.screenshot({ path: OUT + 'st-explore-unstable.png', fullPage: true })
await tc.fill('0.15')
await page.locator('.ps-st-controls').getByRole('radio', { name: 'Mid-line' }).click()
await wait(600)
ro = await readouts()
check(/447\.3\s*ms/.test(ro), 'a mid-line fault: t_cr = 447.3 ms by bisection')
check(/during fault\s+P₂ = 0\.73/.test(await page.locator('.ps-st-pd').innerText()), 'the during-fault curve is P₂ = 0.73 pu')
// playback
await page.getByRole('button', { name: 'Play the swing' }).click()
await wait(700)
const t1 = await text('.ps-st-now')
await wait(500)
const t2 = await text('.ps-st-now')
check(t1 !== t2 && /t = 0\.\d+ s/.test(t2), `Play moves the operating point (${t1.split(' ·')[0]} → ${t2.split(' ·')[0]})`)
await page.getByRole('button', { name: 'Pause' }).click()
await wait(300)
const t3 = await text('.ps-st-now')
await wait(400)
check(t3 === (await text('.ps-st-now')), 'Pause holds it')
await page.locator('.ps-st-scrub input').fill('0.1')
await wait(200)
check(/t = 0\.100 s/.test(await text('.ps-st-now')) && /fault on/.test(await text('.ps-st-now')), 'the time slider moves to t = 0.1 s (fault on)')
check((await page.locator('.ps-st-sld-fault.is-on').count()) === 1, 'the diagram shows the fault while it is on')
await page.locator('.ps-st-scrub input').fill('1')
await wait(200)
check((await page.locator('.ps-st-sld-cb.is-open').count()) === 2, 'after clearing, line 2’s breakers are drawn open')
// small step
await page.locator('.ps-st-controls').getByRole('radio', { name: 'Small step in P_m' }).click()
await wait(500)
ro = await readouts()
check(/1\.137/.test(ro) && /% from the formula/.test(ro), 'small step: measured oscillation 1.137 Hz agrees with the formula')
await page.locator('.ps-st-controls').getByRole('button', { name: 'Reset to the default case' }).click()
await wait(300)
check(await noOverflow(), 'Explore: no horizontal overflow')
await page.screenshot({ path: OUT + 'st-explore-step.png', fullPage: true })

// ── Explore: frequency ───────────────────────────────────────────────────────
console.log('── Explore · frequency')
await page.getByRole('radio', { name: 'Frequency after a load step' }).click()
await wait(500)
ro = await readouts()
check(/−0\.500\s*Hz\/s/.test(ro) && /−0\.368\s*Hz/.test(ro) && /−0\.238\s*Hz/.test(ro), 'load step: RoCoF −0.500 Hz/s, nadir −0.368 Hz, settles at −0.238 Hz')
await page.locator('.ps-slider', { hasText: 'System inertia' }).locator('input').fill('2')
await wait(400)
check(/−1\.250\s*Hz\/s/.test(await readouts()) && /−0\.570\s*Hz/.test(await readouts()), 'H = 2 s: RoCoF −1.250 Hz/s, nadir −0.570 Hz')
await page.locator('.ps-st-controls').getByRole('button', { name: 'Reset to the default case' }).click()
await page.getByLabel('Secondary control (AGC)').check()
await wait(500)
ro = await readouts()
check(/within 5 % of the dip after 24\.7 s/.test(ro), 'with AGC: back within 5 % after 24.7 s')
check((await page.getByRole('radio', { name: '40 s' }).getAttribute('aria-checked')) === 'true', 'switching AGC on widens the window to 40 s')
check(/3 of 6/.test(await acts()), 'AGC completes the “frequency” activity')
check(await noOverflow(), 'frequency: no horizontal overflow')
await page.screenshot({ path: OUT + 'st-explore-freq.png', fullPage: true })

// ── Experiment ───────────────────────────────────────────────────────────────
console.log('── Experiment')
await page.getByRole('tab', { name: 'Experiment' }).click()
await wait(500)
check((await page.locator('.ps-st-exp-item').count()) === 6, 'six experiments')
check((await page.locator('.ps-table').count()) === 0, 'no result before a prediction')
await page.locator('.ps-option', { hasText: 'It falls faster and dips deeper' }).click()
await wait(400)
check(/Your prediction was right/.test(await text('.ps-predict')), 'inertia: the prediction is judged from the simulations')
check(/Initial RoCoF\s*−0\.500 Hz\/s\s*−1\.248 Hz\/s/.test(await text('.ps-table')), 'table: RoCoF −0.500 → −1.248 Hz/s (simulated first step)')
await page.locator('.ps-st-exp-item', { hasText: 'Clear just before' }).click()
await wait(500)
await page.locator('.ps-option', { hasText: 'loses synchronism' }).click()
await wait(500)
check(/Your prediction was right/.test(await text('.ps-predict')), 'clearing 10 % later loses synchronism')
check(/lost synchronism/.test(await text('.ps-table')), 'the table says which run lost synchronism')
await page.screenshot({ path: OUT + 'st-experiment.png', fullPage: true })
await page.locator('.ps-st-exp-item', { hasText: 'A stronger network' }).click()
await wait(500)
await page.locator('.ps-option', { hasText: 'It gets longer' }).click()
await wait(400)
check(/Critical clearing time t_cr\s*210 ms\s*\d+ ms/.test(await text('.ps-table')), 'a stronger network: t_cr compared in the table')
check(/4 of 6/.test(await acts()), 'three experiments complete an activity')
check(await noOverflow(), 'Experiment: no horizontal overflow')

// ── Verify ───────────────────────────────────────────────────────────────────
console.log('── Verify')
await page.getByRole('tab', { name: 'Verify' }).click()
await wait(800)
check((await page.locator('.ps-check--ok').count()) === 6 && (await page.locator('.ps-check--bad').count()) === 0, 'all six hand checks agree with the simulations')
const vt = await page.locator('.ps-panel').innerText()
check(/209\.51 ms/.test(vt) && /209\.50 ms/.test(vt), 'closed-form t_cr 209.51 ms vs bisection 209.50 ms')
check(/90\.316°/.test(vt) && /90\.314°|90\.315°|90\.316°/.test(vt), 'mid-line: δ_cr 90.316° vs the angle at the simulated t_cr')
await page.locator('.ps-num-answer input').first().fill('29.40')
await page.locator('.ps-num-answer').first().getByRole('button', { name: 'Check' }).click()
await page.locator('.ps-num-answer input').nth(1).fill('209.5')
await page.locator('.ps-num-answer').nth(1).getByRole('button', { name: 'Check' }).click()
await wait(300)
check(/2 of 2 answered correctly/.test(await text('.ps-quiz')), 'the student’s own calculations are checked')
check(/5 of 6/.test(await acts()), 'Verify completes its activity')
check(await noOverflow(), 'Verify: no horizontal overflow')
await page.screenshot({ path: OUT + 'st-verify.png', fullPage: true })

// ── Practise ─────────────────────────────────────────────────────────────────
console.log('── Practise')
await page.getByRole('tab', { name: 'Practise' }).click()
await wait(500)
check((await page.locator('.ps-quiz-list > li').count()) === 9, 'nine practice questions')
const answers = ['1.5', '30', '1.14', '209.5', null, '-0.5', '-0.0962', null, null]
const q = page.locator('.ps-quiz-list > li')
for (let k = 0; k < answers.length; k++) {
  if (answers[k] === null) continue
  await q.nth(k).locator('.ps-num-answer input').fill(answers[k])
  await q.nth(k).getByRole('button', { name: 'Check' }).click()
}
await q.nth(4).locator('.ps-option', { hasText: 'loses synchronism' }).click()
await q.nth(7).locator('.ps-option', { hasText: 'faster initial fall' }).click()
await q.nth(8).locator('.ps-option', { hasText: 'AGC' }).click()
await wait(300)
check(/9 of 9 answered correctly/.test(await text('.ps-quiz')), 'all nine answers are checked against the models')
check(/6 of 6/.test(await acts()), 'all six activities done')
check(await noOverflow(), 'Practise: no horizontal overflow')
await page.screenshot({ path: OUT + 'st-practise.png', fullPage: true })

// ── 1280 wide, and reduced motion ────────────────────────────────────────────
console.log('── 1280 px and reduced motion')
const ctx = await browser.newContext({ viewport: { width: 1280, height: 800 }, reducedMotion: 'reduce' })
const p2 = await ctx.newPage()
p2.on('pageerror', (e) => errors.push(String(e)))
for (const m of ['', '?mode=explore', '?mode=experiment', '?mode=verify', '?mode=practise']) {
  await p2.goto(URL + PAGE + m)
  await p2.waitForTimeout(900)
  check(await p2.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth + 1), `1280 px ${m || 'learn'}: no horizontal overflow`)
}
await p2.goto(URL + PAGE + '?mode=explore')
await p2.waitForTimeout(900)
check((await p2.getByRole('button', { name: 'Play the swing' }).count()) === 0 && (await p2.locator('.ps-st-scrub input').count()) === 1, 'reduced motion: no animation, the time slider remains')
await p2.screenshot({ path: OUT + 'st-explore-1280.png', fullPage: true })
await ctx.close()

check(errors.length === 0, `no console errors${errors.length ? `: ${errors.slice(0, 3).join(' | ')}` : ''}`)
await browser.close()
console.log(failures.length ? `\n${failures.length} FAILED` : '\nALL PASSED')
process.exit(failures.length ? 1 : 0)
